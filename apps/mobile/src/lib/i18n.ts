const dictionaries: Record<Language, Messages> = { en, hi };

/** The phone's language decides until the person chooses. Hindi for a Hindi phone, English otherwise. */
export function deviceLanguage(): Language {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale ?? '';
    return locale.toLowerCase().startsWith('hi') ? 'hi' : 'en';
  } catch {
    return 'en';
  }
}

type LanguageState = {
  language: Language;
  /** True once the person picked a language on this phone (login screen or Profile). */
  chosen: boolean;
  setLanguage: (language: Language, chosen?: boolean) => void;
};

export const useLanguageStore = create<LanguageState>()((set) => ({
  language: deviceLanguage(),
  chosen: false,
  setLanguage: (language, chosen = false) => set((state) => ({ language, chosen: state.chosen || chosen })),
}));

/** The texts in the current language, for use in components. Re-renders when the language changes. */
export function useT(): Messages {
  return dictionaries[useLanguageStore((state) => state.language)];
}

/** The texts in the current language, for use outside components (alerts, form rules, helpers). */
export function t(): Messages {
  return dictionaries[useLanguageStore.getState().language];
}

export function messagesFor(language: Language): Messages {
  return dictionaries[language];
}

/** For form rules: the message is looked up when the rule runs, so it is always in the current language. */
export function msg(pick: (m: Messages) => string) {
  return { error: () => pick(t()) };
}

export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'hi';
}
